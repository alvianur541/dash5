import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const file = new URL('../../supabase/migrations/202610110002_usage_identity.sql', import.meta.url);
assert.ok(fs.existsSync(file), 'identity migration exists');
const sql = fs.readFileSync(file, 'utf8');
const db = new PGlite();
await db.exec(`CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,deleted_at timestamptz);
CREATE TABLE public.usage_logs(id bigint PRIMARY KEY,user_nik text);
INSERT INTO auth.users VALUES ('11111111-1111-4111-8111-111111111111','unique@example.test',NULL),('22222222-2222-4222-8222-222222222222','collision@one.test',NULL),('33333333-3333-4333-8333-333333333333','collision@two.test',NULL);
INSERT INTO usage_logs VALUES(1,'unique'),(2,'collision'),(3,'unmatched'),(4,NULL);`);
await db.exec(sql);
const rows = (await db.query('SELECT user_id,is_internal FROM usage_logs ORDER BY id')).rows;
assert.equal(rows[0].user_id,'11111111-1111-4111-8111-111111111111');
assert.deepEqual(rows.slice(1).map(r=>r.user_id),[null,null,null]);
assert.ok(rows.every(r=>r.is_internal===null), 'legacy classification unknown without approved config');
await db.exec(sql);
assert.deepEqual((await db.query('SELECT user_id,is_internal FROM usage_logs ORDER BY id')).rows,rows,'idempotent');
await db.query("SELECT set_config('app.internal_users',$1,false)",['UNIQUE@EXAMPLE.TEST']);
await db.exec(sql);
assert.equal((await db.query('SELECT is_internal FROM usage_logs WHERE id=1')).rows[0].is_internal,true,'approved email config classifies unique match');
assert.equal((await db.query('SELECT is_internal FROM usage_logs WHERE id=2')).rows[0].is_internal,null,'collision stays unknown');
await db.exec(sql);
assert.equal((await db.query('SELECT is_internal FROM usage_logs WHERE id=1')).rows[0].is_internal,true,'rerun preserves classification');
await db.query("SELECT set_config('app.internal_users',$1,false)",['*@example.test']);
await assert.rejects(db.exec(sql),/Invalid internal identity configuration/);
await db.exec('ROLLBACK');
await db.query("SELECT set_config('app.internal_users',$1,false)",['']);
await db.exec("INSERT INTO usage_logs(id,user_nik) VALUES(5,'new')");
assert.equal((await db.query('SELECT is_internal FROM usage_logs WHERE id=5')).rows[0].is_internal,false);
await db.exec("DELETE FROM auth.users WHERE id='11111111-1111-4111-8111-111111111111'");
assert.equal((await db.query('SELECT user_id FROM usage_logs WHERE id=1')).rows[0].user_id,null);
await db.close();
console.log('isolated PGlite: unique-only backfill, collisions/unmatched/null, idempotence, default and FK SET NULL passed');
